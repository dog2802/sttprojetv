"""Коды ошибок, показываемые пользователю.

Цель - чтобы тестер мог сообщить короткий код (например "E102") вместо пересылки всего
лог-файла, и было сразу понятно, в какой части программы искать причину.

Категории:
  E1xx - запуск программы (Application.__init__)
  E2xx - применение настроек на лету, без перезапуска программы (_reload_worker)
  E3xx - хоткей (перехват нажатий клавиш/кнопок мыши)
  E4xx - обработка и доставка распознанного текста
  E5xx - всё остальное (страховочный fallback для непредвиденных ошибок)
"""
from __future__ import annotations

ERROR_DESCRIPTIONS: dict[str, str] = {
    "E101": "Не удалось скачать модель распознавания",
    "E102": "Не удалось загрузить модель распознавания в память",
    "E103": "Не удалось прочитать настройки или словарь терминов",
    "E104": "Выбранный микрофон недоступен",
    "E201": "Не удалось применить новую модель/микрофон",
    "E202": "Не удалось перезапустить хоткей после смены настроек",
    "E301": "Не удалось перехватить нажатия клавиш/кнопок мыши",
    "E401": "Не удалось обработать или доставить распознанный текст",
    "E599": "Неизвестная ошибка",
}


class AppError(Exception):
    """Исключение с кодом ошибки для показа пользователю (см. ERROR_DESCRIPTIONS).

    str(err) уже содержит код и описание - этого достаточно для messagebox/лога без
    дополнительного форматирования на месте вызова."""

    def __init__(self, code: str, detail: str = "") -> None:
        self.code = code
        self.detail = detail
        message = f"[{code}] {ERROR_DESCRIPTIONS.get(code, 'Неизвестная ошибка')}"
        if detail:
            message = f"{message}: {detail}"
        super().__init__(message)
